import { writeFileSync } from 'node:fs';
import { PRESETS } from './sources.mjs';

const LEGACY = {
  abb: 'audiobookbay',
  solid: 'solidtorrents',
  tcsv: 'torrentcsv',
  tgalaxy: 'torrentgalaxy',
  gutenberg: 'gutendex'
};

const registry = {};
const aliases = {};

for (const p of PRESETS) {
  const id = p.file.replace(/\.json$/, '');
  const comic = !!p.comicShelf;
  let media = 'ebook';
  if (comic) media = 'comics';
  else if (p.contentTypes.includes('audiobook') && p.contentTypes.includes('ebook')) media = 'all';
  else if (p.contentTypes.includes('audiobook')) media = 'audiobook';

  let sources = p.sources.map(s => LEGACY[s] || s).join(',');
  // Match live VPS comics shelves (extra indexer coverage).
  if (id === 'manga' || id === 'comics-manga') sources = 'nyaa,knaben,prowlarr';

  const entry = {
    sources,
    debrid: p.downloadMethod,
    profile: p.profile || 'best',
    lang: comic ? (p.language === 'en' ? 'any' : p.language) : p.language,
    languageMode: comic ? 'any' : 'strict',
    media
  };
  if (p.comicShelf) entry.comicShelf = p.comicShelf;
  if (p.audioFormat) entry.audioFormat = p.audioFormat;
  if (p.format) entry.format = p.format;
  registry[id] = entry;
  aliases[p.id] = id;
}

// Short aliases used by hosted VPS comics presets
aliases.comics = 'comics';
aliases.manga = 'manga';
aliases['comics-manga'] = 'comics-manga';
aliases['inkandecho-comics-only-v1'] = 'comics';
aliases['inkandecho-manga-only-v1'] = 'manga';
aliases['inkandecho-comics-manga-best-v1'] = 'comics-manga';

const file = `/** Auto-generated by build-preset-registry.mjs — do not hand-edit. */
export const PRESET_REGISTRY = ${JSON.stringify(registry, null, 2)};

export const PRESET_ALIASES = ${JSON.stringify(aliases, null, 2)};

export function resolvePreset(name) {
  if (!name) return null;
  const key = String(name).trim().toLowerCase().replace(/\\.json$/, '');
  const id = PRESET_ALIASES[key] || key;
  return PRESET_REGISTRY[id] || null;
}

export function applyPresetToUrl(url, body = {}) {
  const name = url.searchParams.get('preset')
    || url.searchParams.get('shelfbridgePreset')
    || body.preset
    || body.shelfbridgePreset
    || null;
  const conf = resolvePreset(name);
  if (!conf) return { url, body, applied: null };
  if (conf.sources) url.searchParams.set('sources', conf.sources);
  if (conf.media) url.searchParams.set('media', conf.media);
  if (conf.comicShelf) url.searchParams.set('comicShelf', conf.comicShelf);
  if (conf.debrid) url.searchParams.set('debrid', conf.debrid);
  if (conf.lang) url.searchParams.set('lang', conf.lang);
  if (conf.languageMode) url.searchParams.set('languageMode', conf.languageMode);
  if (conf.profile) url.searchParams.set('profile', conf.profile);
  if (conf.audioFormat) url.searchParams.set('audioFormat', conf.audioFormat);
  const presetId = String(name).replace(/\\.json$/, '');
  url.searchParams.set('preset', presetId);
  const next = { ...body };
  if (conf.media === 'comics') {
    next.media = 'comics';
    next.contentType = 'comics';
    if (conf.comicShelf) next.comicShelf = conf.comicShelf;
  } else if (conf.media) {
    next.media = conf.media;
    if (!next.contentType || next.contentType === 'ebook') {
      next.contentType = conf.media === 'all' ? 'ebook' : conf.media;
    }
  }
  if (conf.debrid) next.debrid = conf.debrid;
  if (conf.sources) next.sources = conf.sources;
  if (conf.profile) next.profile = conf.profile;
  if (conf.lang) next.lang = conf.lang;
  if (conf.languageMode) next.languageMode = conf.languageMode;
  if (conf.audioFormat) next.audioFormat = conf.audioFormat;
  next.preset = presetId;
  return { url, body: next, applied: conf, preset: presetId };
}
`;

writeFileSync(new URL('./preset-registry.mjs', import.meta.url), file);

const base = 'https://raw.githubusercontent.com/drewk312/shelfbridge-presets/main/';
const md = `# Import ALL (once) — then server updates forever

Paste each URL in Ink & Echo / Sumiyo → Sources → Add from link.
Each becomes a switch. After this one pass, we update routing on the VPS via \`preset=\` — no re-add.

## Recommended starter (turn the rest off until needed)

1. ${base}direct-ebooks.json
2. ${base}comics.json
3. ${base}manga.json
4. ${base}audiobooks.json
5. ${base}mobilism.json

## Full list (${PRESETS.length})

${PRESETS.map(p => `- **${p.name}** (\`${p.downloadMethod}\`): ${base}${p.file}`).join('\n')}

## Live comics mirrors (same content)

- https://search.inkecho.duckdns.org/presets/comics.json
- https://search.inkecho.duckdns.org/presets/manga.json
- https://search.inkecho.duckdns.org/presets/comics-manga.json
`;

writeFileSync(new URL('./IMPORT-ALL.md', import.meta.url), md);
console.log('Wrote preset-registry.mjs + IMPORT-ALL.md for', PRESETS.length, 'presets');
